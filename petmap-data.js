/* 게임좌표 → 지도 픽셀 */
(function(){
  function solve3(M, v){ /* 3x3 연립방정식 (가우스 소거) */
    const a = M.map((r, i) => r.concat([v[i]]));
    for(let c = 0; c < 3; c++){
      let p = c; for(let r = c + 1; r < 3; r++) if(Math.abs(a[r][c]) > Math.abs(a[p][c])) p = r;
      [a[c], a[p]] = [a[p], a[c]];
      for(let r = 0; r < 3; r++){ if(r === c) continue; const f = a[r][c]/a[c][c]; for(let k = c; k < 4; k++) a[r][k] -= f*a[c][k]; }
    }
    return [a[0][3]/a[0][0], a[1][3]/a[1][1], a[2][3]/a[2][2]];
  }
  function fitAffine(pts){
    const N = [[0,0,0],[0,0,0],[0,0,0]], bx = [0,0,0], by = [0,0,0];
    pts.forEach(([x, y, px, py]) => { const r = [x, y, 1]; for(let i = 0; i < 3; i++){ for(let j = 0; j < 3; j++) N[i][j] += r[i]*r[j]; bx[i] += r[i]*px; by[i] += r[i]*py; } });
    return { ax:solve3(N, bx), ay:solve3(N, by) };
  }
  const aff = (m, x, y) => [m.A.ax[0]*x + m.A.ax[1]*y + m.A.ax[2], m.A.ay[0]*x + m.A.ay[1]*y + m.A.ay[2]];
  window.PETMAP.forEach(m => {
    m.A = fitAffine(m.pts);
    m.res = m.pts.map(([x, y, px, py]) => { const p = aff(m, x, y); return [x, y, px - p[0], py - p[1]]; });
  });
  /* 기준점 근처는 그 점의 어긋남을 그대로 따라가고, 멀어질수록 보정이 줄어들어요 */
  window.PETMAP_TO_PX = function(m, x, y){
    const base = aff(m, x, y);
    let sw = 1/(60*60), sx = 0, sy = 0;
    for(const [gx, gy, rx, ry] of m.res){
      const d2 = (gx - x)*(gx - x) + (gy - y)*(gy - y);
      if(d2 < 0.25) return [base[0] + rx, base[1] + ry];
      const w = 1/d2; sw += w; sx += w*rx; sy += w*ry;
    }
    return [base[0] + sx/sw, base[1] + sy/sw];
  };
  /* 지도에서 '동·남' 방향이 화면에서 어느 쪽인지 (나침반 표시용) */
  window.PETMAP_AXES = function(m){
    const o = aff(m, 0, 0), e = aff(m, 100, 0), s = aff(m, 0, 100);
    return { east:[e[0] - o[0], e[1] - o[1]], south:[s[0] - o[0], s[1] - o[1]] };
  };
  /* 획득처 글에서 지도와 좌표 찾기 */
  window.PETMAP_FIND = function(how){
    how = String(how || "");
    const re = /([가-힣A-Za-z ]+?)\s*\(\s*(\d+)\s*[，,]\s*(\d+)\s*\)/g;
    let m;
    while((m = re.exec(how))){
      const place = m[1].replace(/\s+/g, " ").trim();
      if(/층$/.test(place)) continue;
      const map = window.PETMAP.slice().sort((a, b) => Math.max(...b.match.map(s => s.length)) - Math.max(...a.match.map(s => s.length)))
        .find(mp => mp.match.some(k => place.endsWith(k) || place === k));
      if(map) return { map, x:Number(m[2]), y:Number(m[3]) };
    }
    return null;
  };
})();

